// Regenerates src/generated/ from the contract and the error catalogue (IP-26 D3, D9).
//
// Inputs, both read from the repository rather than copied here:
//   - api/openapi.yaml, the source of truth for the wire format (ADR-0010);
//   - docs/product/error-catalog.md section 2, the client action for each code.
//
// Outputs, all under src/generated/ and never hand-edited:
//   - schema.ts      the contract's types, from openapi-typescript;
//   - routes.ts      operationId -> method and path, and the contract's version;
//   - catalogue.ts   code -> status, retry verdict and client action;
//   - errors.ts      one QuotacoreError subclass per code.
//
// It fails, writing nothing, when the catalogue and the contract's ErrorCode enum disagree, so a
// code added to one and not the other cannot reach the SDK.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const repo = join(pkg, "..", "..");
const out = join(pkg, "src", "generated");

const BANNER =
  "// Code generated by sdk/typescript/scripts/generate.mjs from the repository. DO NOT EDIT.\n" +
  "// Regenerate with `npm run generate`; see BOUNDARY.md.\n";

const spec = yaml.load(readFileSync(join(repo, "api", "openapi.yaml"), "utf8"));

// The types. The parsed document is passed as an object so its UTF-8 text is never re-decoded.
const schema = astToString(await openapiTS(spec, { alphabetize: false }));

// The route table. Only routes under /v1/ are the SDK's; probes, metrics and docs are not.
const routes = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (!path.startsWith("/v1/")) continue;
  for (const method of ["get", "post", "patch", "put", "delete"]) {
    const op = item[method];
    if (!op) continue;
    const headers = (op.parameters ?? [])
      .map((p) => (p.$ref ? resolve(p.$ref) : p))
      .filter((p) => p.in === "header")
      .map((p) => p.name);
    routes.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      admin: path.startsWith("/v1/admin/"),
      idempotent: headers.includes("Idempotency-Key"),
    });
  }
}
routes.sort((a, b) => a.id.localeCompare(b.id));

function resolve(ref) {
  return ref
    .replace(/^#\//, "")
    .split("/")
    .reduce((node, key) => node[key], spec);
}

// The catalogue. Every row of the tables in section 2 whose first cell is a code.
const catalogueText = readFileSync(join(repo, "docs", "product", "error-catalog.md"), "utf8");
const section = catalogueText.slice(
  catalogueText.indexOf("## 2. Catalogue"),
  catalogueText.indexOf("## 3."),
);
const catalogue = [];
for (const line of section.split("\n")) {
  const m = /^\| `([a-z_]+)` \| (\d{3}) \|/.exec(line);
  if (!m) continue;
  const cells = line.split("|").slice(1, -1).map((c) => c.trim());
  catalogue.push({
    code: m[1],
    status: Number(m[2]),
    retryable: plain(cells[4]),
    clientAction: plain(cells[5]),
  });
}

function plain(cell) {
  return cell.replace(/\*\*/g, "").replace(/`/g, "");
}

const enumCodes = spec.components.schemas.ErrorCode.enum;
const catalogueCodes = catalogue.map((c) => c.code);
const missing = enumCodes.filter((c) => !catalogueCodes.includes(c));
const extra = catalogueCodes.filter((c) => !enumCodes.includes(c));
if (missing.length || extra.length) {
  console.error(
    `generate: the catalogue and the contract disagree; in the contract only: [${missing}], in the catalogue only: [${extra}]`,
  );
  process.exit(1);
}
catalogue.sort((a, b) => enumCodes.indexOf(a.code) - enumCodes.indexOf(b.code));

function className(code) {
  const pascal = code
    .split("_")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
  return pascal.endsWith("Error") ? pascal : `${pascal}Error`;
}

const routesTs =
  BANNER +
  `\n/** The contract version this package was generated from (\`info.version\`). */\n` +
  `export const contractVersion = ${JSON.stringify(spec.info.version)};\n\n` +
  `/** Every \`/v1/\` operation in the contract, by operationId. */\n` +
  `export const routes = {\n` +
  routes
    .map(
      (r) =>
        `  ${r.id}: { method: ${JSON.stringify(r.method)}, path: ${JSON.stringify(r.path)}, admin: ${r.admin}, idempotent: ${r.idempotent} },`,
    )
    .join("\n") +
  `\n} as const;\n\n` +
  `export type OperationId = keyof typeof routes;\n` +
  `export type AdminOperationId = {\n  [K in OperationId]: (typeof routes)[K]["admin"] extends true ? K : never;\n}[OperationId];\n`;

const catalogueTs =
  BANNER +
  `\n/** Every code in the contract's \`ErrorCode\` enum, in its order. */\n` +
  `export const errorCodes = ${JSON.stringify(enumCodes, null, 2)} as const;\n\n` +
  `export type ErrorCode = (typeof errorCodes)[number];\n\n` +
  `export interface CatalogueEntry {\n  /** The documented HTTP status. */\n  readonly status: number;\n` +
  `  /** The catalogue's retry verdict, verbatim. The SDK's own retry policy is in retry.ts. */\n  readonly retryable: string;\n` +
  `  /** What the catalogue tells a client to do. */\n  readonly clientAction: string;\n}\n\n` +
  `/** docs/product/error-catalog.md section 2, by code. */\n` +
  `export const catalogue: { readonly [C in ErrorCode]: CatalogueEntry } = {\n` +
  catalogue
    .map(
      (c) =>
        `  ${c.code}: {\n    status: ${c.status},\n    retryable: ${JSON.stringify(c.retryable)},\n    clientAction: ${JSON.stringify(c.clientAction)},\n  },`,
    )
    .join("\n") +
  `\n};\n`;

const errorsTs =
  BANNER +
  `\nimport { QuotacoreError } from "../errors.js";\nimport type { ErrorCode } from "./catalogue.js";\n\n` +
  catalogue
    .map(
      (c) =>
        `/** \`${c.status} ${c.code}\`. ${c.clientAction.replace(/\*\//g, "* /")} */\n` +
        `export class ${className(c.code)} extends QuotacoreError {\n  declare readonly code: ${JSON.stringify(c.code)};\n}\n`,
    )
    .join("\n") +
  `\n/** The class for each code. A code not listed here is raised as a plain QuotacoreError. */\n` +
  `export const errorClasses: { readonly [C in ErrorCode]: typeof QuotacoreError } = {\n` +
  catalogue.map((c) => `  ${c.code}: ${className(c.code)},`).join("\n") +
  `\n};\n`;

mkdirSync(out, { recursive: true });
writeFileSync(join(out, "schema.ts"), BANNER + "\n" + schema);
writeFileSync(join(out, "routes.ts"), routesTs);
writeFileSync(join(out, "catalogue.ts"), catalogueTs);
writeFileSync(join(out, "errors.ts"), errorsTs);
console.log(`generate: ${routes.length} routes, ${catalogue.length} codes, contract ${spec.info.version}`);
