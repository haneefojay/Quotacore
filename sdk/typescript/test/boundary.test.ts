// IP-26 DoD 1 and DoD 10, and D13 and D17: what is generated is separate from what is written,
// the package has no runtime dependency, its version is the contract's, and it states its Node
// range.

import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import yaml from "js-yaml";
import { contractVersion } from "../src/index.js";
import { packageFile, repoFile } from "./paths.js";

const banner = "// Code generated by sdk/typescript/scripts/generate.mjs from the repository. DO NOT EDIT.";
const pkg = JSON.parse(readFileSync(packageFile("package.json"), "utf8"));

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : [p];
  });
}

test("every generated file carries the banner, and no hand-written file does", () => {
  const all = files(packageFile("src"));
  const generated = all.filter((f) => f.includes(`${join("src", "generated")}`));
  assert.ok(generated.length >= 4);
  for (const f of all) {
    const starts = readFileSync(f, "utf8").startsWith(banner);
    assert.equal(starts, generated.includes(f), f);
  }
});

test("BOUNDARY.md names the generated directory and the command that regenerates it", () => {
  const doc = readFileSync(packageFile("BOUNDARY.md"), "utf8");
  assert.match(doc, /src\/generated\//);
  assert.match(doc, /npm run generate/);
});

test("no runtime dependency", () => {
  assert.deepEqual(pkg.dependencies ?? {}, {});
  assert.equal(pkg.peerDependencies, undefined);
});

test("the package version is the contract version", () => {
  const spec = yaml.load(readFileSync(repoFile("api/openapi.yaml"), "utf8")) as { info: { version: string } };
  assert.equal(pkg.version, spec.info.version);
  assert.equal(contractVersion, spec.info.version);
});

test("the Node range is stated, and this Node is inside it", () => {
  assert.equal(pkg.engines.node, ">=22");
  assert.ok(Number(process.versions.node.split(".")[0]) >= 22);
});
